"""문서에 날짜가 있나 — 모델의 0건 응답을 검증하는 독립 근거.

`gemma4:e2b` 가 일정 3건짜리 문서에 0건을 냈다 (설계 §2.1). 모델 출력만 믿으면
그것이 `no_schedule` 로 나가고, 관리자는 "일정이 없다" 는 답을 받아 재시도하지 않는다.

**거짓 양성을 감수한다.** 회의록의 작성일, 규정의 시행일처럼 일정이 아닌 날짜가
거짓 500 을 만든다. 일정이 든 문서를 "없다" 고 답하는 쪽이 더 나쁘다 (설계 §3.3).

전화번호(`010-1234-5678`), 수량(`30/개`), 분수·비율(`1/2 분기`, `2/3 이상`)을
날짜로 읽지 않는 것이 정확도의 핵심이다 — 그것들이 통과하면 거의 모든 문서가
날짜를 가진 것이 되어 검사가 무의미해진다.

**월만 있는 표기는 일부러 잡지 않는다.** `8월 중`·`9월 정기 워크숍`처럼 일(day)이
없으면 시작·종료 시각(`startAt`/`endAt`)을 만들 수 없다 — 프롬프트가 종일 일정도
`그날T00:00`을 요구하는데 "그날"이 없기 때문이다. 즉 이런 문서에서 모델이 0건을
내는 것은 정당하다. 여기서 `True`를 내면 그 문서는 재시도해도 영구히 500이 된다 —
관리자가 몇 번을 다시 올려도 같은 결과이고, 그때마다 원본·파싱 파일이 지워진다.
거짓 양성 중에서도 가장 나쁜 종류이므로, 이 검사는 "일(day) 없는 날짜"를
의도적으로 놓친다.
"""

from __future__ import annotations

import re

# "1/2 분기", "2/3 이상"처럼 분수·비율 뒤에 붙는 단위 낱말. 이 낱말이 뒤따르면
# 숫자/숫자 표기라도 날짜가 아니다 — 세 번째 패턴의 종결 lookahead가 공백만 보고
# 통과시키기 때문에 별도로 배제해야 한다. 나중에 목록을 넓힐 자리이지, 지울 자리가
# 아니다.
#
# 두 글자 이상 낱말과 한 글자 낱말을 나눈다 — 기준은 "무엇과 더 자주 겹치나" 다.
# 한 글자 낱말(개·명·배)은 "개최"·"명단"·"배포"처럼 다른 낱말의 접두어와 겹치는
# 빈도가 압도적이라, 뒤에 한글 음절이 이어지지 않을 때만(그 낱말에서 끝날 때만)
# 배제한다 — `(?![가-힣])`.
# 두 글자 이상 낱말(분기·이상·이하·미만·정도·수준)은 그 자체로 단위 표현이라
# 조사가 붙는 형태(`이상은`·`분기에`)가 흔하다. 그런데 "이상민"·"정도영"처럼
# 사람 이름의 접두어와도 겹친다 — 조사와 이름 음절을 정규식이 갈라야 한다.
# 그래서 "낱말 + (조사 한 글자 | 공백·부호 | 문자열 끝)" 일 때만 배제한다.
_LONG_NON_DATE_UNIT_WORDS = "분기|이상|이하|미만|정도|수준"
_SHORT_NON_DATE_UNIT_WORDS = "배|개|명"
# 긴 배제 낱말 뒤에 이 조사 중 하나가 오면 "이상은"처럼 단위+조사로 본다.
# 이 집합에 없는 한글 음절(이름 등)이 이어지면 배제하지 않는다.
_TRAILING_PARTICLES = "은는이가을를에의로도만과와"

_PATTERNS = (
    # 8월 12일 · 12월 31일
    re.compile(r"\d{1,2}\s*월\s*\d{1,2}\s*일"),
    # 2026-08-12 · 2026.08.12 · 2026/08/12
    re.compile(r"(?<!\d)\d{4}\s*[-./]\s*\d{1,2}\s*[-./]\s*\d{1,2}(?!\d)"),
    # 8/5 · 08-12 — 뒤에 숫자·하이픈·슬래시가 이어지지 않는 것만 허용해
    # 전화번호(010-1234-5678)와 수량(30/개)을 걸러낸다. 날짜는 보통 공백,
    # 종결부호, "일/월" 같은 날짜 단위, 괄호가 뒤따른다.
    # 종결 lookahead(`\s*(?=...)`)는 공백이 있으면 그 공백 자체로 만족해
    # "1/2 분기"의 "분기"까지는 보지 않는다 — 그래서 단위 낱말은 별도의
    # 부정 lookahead로 앞서 걸러낸다. 긴 낱말은 조사·어미가 이어질 때만
    # 배제해 "8/5 이상민 과장" 같은 이름 접두어 충돌을 피하고, 짧은 낱말은
    # `(?![가-힣])`로 낱말이 거기서 끝날 때만 배제해 "8/5 개최"·"8/5 명단
    # 제출" 같은 접두어 충돌을 피한다.
    re.compile(
        r"(?<![\d\-/])\d{1,2}\s*[-/]\s*\d{1,2}(?![\d\-/])"
        rf"(?!\s*(?:{_LONG_NON_DATE_UNIT_WORDS})(?:[{_TRAILING_PARTICLES}]|[\s,.)]|$))"
        rf"(?!\s*(?:{_SHORT_NON_DATE_UNIT_WORDS})(?![가-힣]))"
        r"\s*(?=[)\s(일월,.]|$)"
    ),
)


def has_date_pattern(markdown: str) -> bool:
    return any(pattern.search(markdown) for pattern in _PATTERNS)


# `has_any_date_evidence` 전용 — `has_date_pattern` 의 정규식·테스트는 손대지 않는다.
_LENIENT_PATTERNS = (
    re.compile(r"\d{1,2}\s*월"),            # 월 단독 — "8월 행사"처럼 일과 떨어진 월 파편
    re.compile(r"\d{1,2}\s*일(?!요일)"),     # 일 단독 — "12일에 진행"처럼 월과 떨어진 일 파편.
                                             # "요일"(화요일 등)과 안 겹치게 부정 lookahead로 뺀다
    re.compile(r"\d{4}\s*년"),               # 연도 표기 — "2026년 계획". "년" 없이 숫자 4개만으로는
                                             # 전화번호(010-1234-5678)와 안 갈라지므로 요구한다
    re.compile(r"[월화수목금토일]요일"),      # 요일 전체 표기 — "화요일"
    re.compile(r"[(（][월화수목금토일][)）]"),  # 요일 축약 — "(수)"·"(목)"
    re.compile(r"내일|모레|익일|차주|다음\s*주|이번\s*주"),  # 상대 표현
)


def has_any_date_evidence(markdown: str) -> bool:
    """날짜로 읽힐 만한 것이 하나라도 있나 — `has_date_pattern` 보다 헐렁하다.

    쓰임이 반대다. `has_date_pattern` 은 모델이 0건을 냈을 때 "이 문서에
    정말 일정이 없나" 를 묻고, 헐렁하면 그 문서가 영구히 500 이 된다.
    이 함수는 모델이 일정을 냈을 때 "근거가 있나" 를 묻고, 엄격하면
    진짜 일정이 조용히 사라진다. 그래서 임계가 정반대다.

    예: "# 8월 행사 안내" 와 "- 12일 워크숍" 이 떨어져 있는 문서.
    has_date_pattern 은 False 지만 모델은 문맥으로 8월 12일을 정당하게
    뽑는다. 그것을 버리면 안 된다.

    `3일간`·`5일 이내` 처럼 기간·기한 표현도 걸리지만 일부러 막지 않는다 —
    여기서 True 가 나온다고 일정이 만들어지는 것이 아니라, 모델이 이미 낸
    일정을 살릴지만 정한다.
    """
    if has_date_pattern(markdown):
        return True
    return any(pattern.search(markdown) for pattern in _LENIENT_PATTERNS)
