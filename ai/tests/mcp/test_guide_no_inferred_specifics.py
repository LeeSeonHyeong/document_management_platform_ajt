"""guide 가 「원문에 없는 구체값을 추정으로 채우는 것」을 금지한다.

## 실측 (2026-08-06, job 44 산출물 검수)

원본문서 「공통 프로젝트 산출물 제출 안내.pdf」에는 기한이 **「8/10(월) 12:00」** 뿐이고
연도가 없다. 에이전트가 위키에 **「2025년 8월 10일(월)」** 이라고 썼다 — 연도를 추정으로
채웠고 틀렸다 (2025-08-10 은 일요일이라 자기모순, 실제로는 2026-08-10 월요일).
제출 기한 안내에서 연도가 1년 틀리면 「작년 공지」로 읽혀 실사용 피해가 난다.

이 부류는 지금 어느 방어선에도 안 걸린다는 것까지 실측했다:

* `lint` 인용문 대조 — 각주 밖 본문이라 대상이 아니다 (10개 각주는 전부 원문과 일치했다)
* 에이전트 자기검증 — 관리자 채팅으로 「원본과 다르거나 안 맞는 내용이 있는지」물었더니
  **자기도 연도를 빼고 비교해** "제출 기한(8/10 월 12:00) — 일치" 로 판정했다.
  원문과 겹치는 부분만 대조하므로 **추가된 값은 대조 자체에서 빠진다**

기계로 못 잡으니 애초에 쓰지 않게 지시한다. 규칙의 자리는 guide 다 — 두 런타임이
같은 지침을 받는 유일한 곳이고(`base.py::ingest_instruction` docstring), 「근거 없는
내용을 쓰지 않는다」가 이미 있는 금지 절이 정확한 위치다.
"""

from wiki_mcp.tools.guide import GUIDE_TEXT


def test_금지_절이_추정_구체값을_명시적으로_막는다():
    """「근거 없는 내용」만으로는 부족했다 — 모델은 연도 추정을 「근거 있는 보완」으로
    여긴다. 연도·날짜·수치를 집어 말해야 한다."""
    assert "## 금지" in GUIDE_TEXT
    forbidden = GUIDE_TEXT.split("## 금지", 1)[1]
    for word in ("연도", "수치", "추정"):
        assert word in forbidden, f"금지 절에 「{word}」 언급이 없다"


def test_원문_표기를_그대로_쓰라는_예시가_있다():
    """추상 규칙만으로는 안 지켜진다 — 실측 사례(8/10)를 예시로 박는다."""
    assert "8/10" in GUIDE_TEXT
